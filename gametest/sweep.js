// Writes gametest/mc/src/fdl_test/sweep.mcb, one function per rarity, sweep/<rarity>. Each rolls every item loot table of the rarity once per variant
// and checks that something came out and that every item carries a DungeonLootId. Run by run.js before the mcb build, the output is gitignored.
// A table is data/foxcraft_dungeon_loot/loot_table/item/<rarity>/<item>.json, or <item>/drop.json for an item with extra tables such as the
// Hammer of Sol expiry. Variants are the scores of satyrn.fdl.loot.variant the table's conditions test, and the unset score on top.
// loot spawn runs with the command's entity as this, so the rolls run as a marker that holds the score.
const fs = require("node:fs");
const path = require("node:path");

const RARITIES = ["common", "uncommon", "rare", "epic", "mythic"];
const VARIANT = "satyrn.fdl.loot.variant";

// Every number the variant score is tested against, a plain value or the min and max of a range
function variantsOf(node, out = new Set()) {
	if (Array.isArray(node)) node.forEach((n) => variantsOf(n, out));
	else if (node && typeof node === "object") {
		if (node.scores && VARIANT in node.scores) {
			const v = node.scores[VARIANT];
			for (const n of typeof v === "number" ? [v] : [v.min, v.max]) if (Number.isInteger(n)) out.add(n);
		}
		Object.values(node).forEach((n) => variantsOf(n, out));
	}
	return out;
}

function tablesOf(root, rarity) {
	const dir = path.join(root, "data", "foxcraft_dungeon_loot", "loot_table", "item", rarity);
	const tables = [];
	for (const entry of fs.readdirSync(dir, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name))) {
		if (entry.isFile() && entry.name.endsWith(".json")) tables.push({ id: `item/${rarity}/${entry.name.slice(0, -5)}`, file: path.join(dir, entry.name) });
		else if (entry.isDirectory() && fs.existsSync(path.join(dir, entry.name, "drop.json"))) tables.push({ id: `item/${rarity}/${entry.name}/drop`, file: path.join(dir, entry.name, "drop.json") });
	}
	return tables;
}

function generateSweep(root) {
	const lines = [
		"# Generated by gametest/sweep.js, do not edit. Rolls every item loot table of each rarity, once per variant of the loot variant score.",
		"",
	];
	lines.push(
		"# Run as an item entity. An id, when there is one, is a positive number",
		"function check_id {",
		"\tscoreboard players set #id fdl_test 1",
		"\texecute if data entity @s Item.components.\"minecraft:custom_data\".DungeonLootId store result score #id fdl_test run data get entity @s Item.components.\"minecraft:custom_data\".DungeonLootId",
		"\texecute unless score #id fdl_test matches 1.. run scoreboard players set #bad fdl_test 1",
		"}",
		"",
	);
	let rolls = 0;
	for (const rarity of RARITIES) {
		lines.push(`function ${rarity} {`, "\tfunction fdl_test:lib/begin", "\tfunction fdl_test:lib/flat");
		lines.push("\texecute at @e[tag=tt.origin,limit=1] run summon minecraft:marker ~3 ~ ~ {Tags:[\"tt\",\"tt.holder\"]}");
		for (const t of tablesOf(root, rarity)) {
			const json = JSON.parse(fs.readFileSync(t.file, "utf8"));
			const variants = [null, ...[...variantsOf(json)].filter((n) => n > 0).sort((a, b) => a - b)];
			for (const v of variants) {
				const label = `${t.id}${v === null ? "" : ` variant ${v}`}`;
				lines.push(`\t# ${label}`);
				lines.push(v === null ? `\tscoreboard players reset @e[tag=tt.holder] ${VARIANT}` : `\tscoreboard players set @e[tag=tt.holder] ${VARIANT} ${v}`);
				lines.push(`\texecute as @e[tag=tt.holder] at @s run loot spawn ~ ~ ~ loot foxcraft_dungeon_loot:${t.id}`);
				lines.push("\texecute store success score #none fdl_test at @e[tag=tt.holder] unless entity @e[type=minecraft:item,distance=..2]");
				lines.push(`\texecute if score #none fdl_test matches 1 run say gt FAIL ${label} rolled nothing`);
				lines.push("\texecute if score #none fdl_test matches 1 run scoreboard players set #ok fdl_test 0");
				lines.push("\tscoreboard players set #bad fdl_test 0");
				lines.push("	execute at @e[tag=tt.holder] as @e[type=minecraft:item,distance=..2] run function fdl_test:sweep/check_id");
				lines.push(`\texecute if score #bad fdl_test matches 1 run say gt FAIL ${label} gave an item with a bad DungeonLootId`);
				lines.push("\texecute if score #bad fdl_test matches 1 run scoreboard players set #ok fdl_test 0");
				lines.push("\texecute at @e[tag=tt.holder] run kill @e[type=minecraft:item,distance=..2]");
				rolls += 1;
			}
		}
		lines.push("\tscoreboard players reset @e[tag=tt.holder] " + VARIANT, "}", "");
	}
	fs.writeFileSync(path.join(root, "gametest", "mc", "src", "fdl_test", "sweep.mcb"), lines.join("\n"));
	return rolls;
}

module.exports = { generateSweep };
